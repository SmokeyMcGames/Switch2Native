static constexpr auto make_sensor_descriptor(bool motion) {
    sensor_hid::Descriptor result;
    if (motion) {
        result.sensor(0x10, true);
        result.sensor(0x11, false);
    }
    // The Xbox filter rewrites every joystick on the gamepad root. Put the
    // assignable Home button on this unfiltered companion instead.
    result.add({0x05, 0x01, 0x09, 0x04, 0xa1, 0x01, 0x85, 0x05,
                0x05, 0x09, 0x09, 0x01, 0x15, 0x00, 0x25, 0x01,
                0x35, 0x00, 0x45, 0x00, 0x65, 0x00, 0x55, 0x00,
                0x75, 0x01, 0x95, 0x01, 0x81, 0x02,
                0x75, 0x07, 0x95, 0x01, 0x81, 0x03, 0xc0});
    // Separate diagnostic collection; sensor HID owns its own two collections.
    result.add({0x06, 0x00, 0xff, 0x09, 0x01, 0xa1, 0x01, 0x85, 0xe3, 0x15, 0,    0x26, 0xff,
                0,    0x35, 0,    0x45, 0,    0x65, 0,    0x55, 0,    0x75, 8,    0x95, 95,
                0x09, 1,    0xb1, 2,    0x85, 0xe5, 0x95, 63,   0x09, 2,    0xb1, 2,    0xc0});
    return result;
}
